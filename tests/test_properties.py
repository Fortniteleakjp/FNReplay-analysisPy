from __future__ import annotations

import pytest

from fnreplay.unreal.archives import NetBitReader
from fnreplay.unreal.enums import EngineNetworkVersionHistory
from fnreplay.unreal.models import (
    FDateTime,
    FGameplayTag,
    FGameplayTagContainer,
    FHitResult,
    FPredictionKey,
    FText,
)


def _reader(raw: bytes, bit_count: int, version=EngineNetworkVersionHistory.HISTORY_INITIAL):
    reader = NetBitReader(raw, bit_count)
    reader.engine_network_version = version
    return reader


@pytest.mark.parametrize("raw,bit_count", [(b"\xFB\x80", 16), (b"\xAD\x8A", 16)])
def test_gameplay_tag(raw: bytes, bit_count: int) -> None:
    reader = _reader(raw, bit_count)
    FGameplayTag().serialize(reader)
    assert reader.at_end()
    assert not reader.is_error


